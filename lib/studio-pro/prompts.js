/**
 * Промпт для режима SURPRISE
 */
export function getSurprisePrompt(pose = 'stand') {
  const hanging = pose === 'hang';
  return `РЕЖИМ: Шар-сюрприз (surprise), положение: ${hanging ? 'висит' : 'стоит'}

КОМНАТА — как у напольной композиции:
- Стена: светлая тёплая beige-grey
- Белый плинтус
- Светлый серо-бежевый ламинат

${hanging ? `ПОЛОЖЕНИЕ — ВИСИТ:
- Шар висит на ленте сверху кадра
- На пол его НЕ ставить, подставку НЕ добавлять
- Лента, бант и то, что внутри шара, остаются
- На ламинате только мягкая тень, шар пола не касается` : `ПОЛОЖЕНИЕ — СТОИТ:
- Шар стоит на своей подставке у плинтуса
- Подставка, кольцо-основание, чёрный цилиндр, белая платформа, стойка с купюрами — это ТОВАР, не мебель
- Купюры и тубус с деньгами НЕ удалять
- Чужой стол под товаром убрать, свою подставку оставить на ламинате`}

Подходит для:
- Прозрачного шара с шариками внутри
- Гиганта «лопни меня»
- Шара с деньгами`;
}

