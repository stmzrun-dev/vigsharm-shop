/**
 * Базовый промпт - применяется ВСЕГДА
 */
export function getBasePrompt() {
  return `Ты редактируешь коммерческую фотографию реального товара VigSharm (воздушные шары, букеты, декор).

АБСОЛЮТНЫЕ ПРАВИЛА (НАРУШЕНИЕ НЕДОПУСТИМО):

1. ТОВАР НЕИЗМЕНЕН:
   - Количество элементов (шаров, цветов) - СТРОГО как на оригинале
   - Цвета - СТРОГО как на оригинале
   - Гендерный код и палитра аудитории - СТРОГО как на оригинале
     (розовое/«для девочки» не уводить в синее; синее/«для мальчика» не уводить в розовое)
   - Форма, размер, пропорции - СТРОГО как на оригинале
   - Надписи, цифры, буквы, имена на товаре - СТРОГО как на оригинале
   - Персонажи, фигуры - СТРОГО как на оригинале
   - Композиция, расположение - СТРОГО как на оригинале

2. ЗАПРЕЩЕНО:
   - Добавлять элементы (шары, цветы, декор)
   - Удалять элементы
   - Менять количество элементов
   - Менять цвета
   - Менять гендерную палитру (розовое↔синее, «мальчик»↔«девочка»)
   - Менять надписи/цифры/имена получателя
   - Менять персонажей
   - Изменять композицию
   - Растягивать/деформировать объекты
   - Превращать один товар в другой

3. РАЗРЕШЕНО МЕНЯТЬ ТОЛЬКО:
   - Фон (стена, пол)
   - Освещение (мягкое, естественное)
   - Цветовой баланс (нейтральный, без желтизны)

4. КАЧЕСТВО:
   - Фотография должна выглядеть РЕАЛЬНО, а НЕ как 3D render
   - Без пластикового глянца
   - Без искусственного HDR
   - Тени мягкие, естественные
   - Освещение студийное, нейтральное

5. ЭТАЛОННЫЙ ФОН VIGSHARM:
   - Стена: светлая тёплая beige-grey (бежево-серая)
   - Плинтус: белый аккуратный
   - Пол: светлый серо-бежевый ламинат
   - Чистая студия без лишних предметов`;
}

