/**
 * Собрать финальный промпт для AI
 * @param {string} mode - Режим обработки (StudioMode)
 * @param {string} userInstructions - Дополнительные пожелания пользователя
 * @returns {string} Полный промпт для отправки в AI
 */
export function buildPrompt(mode, userInstructions = '') {
  const base = getBasePrompt();
  
  let modePrompt = '';
  switch (mode) {
    case 'wall_only':
      modePrompt = getWallOnlyPrompt();
      break;
    case 'unit_balloon':
      modePrompt = getUnitBalloonPrompt();
      break;
    case 'handheld_bouquet':
      modePrompt = getHandheldBouquetPrompt();
      break;
    case 'floor':
      modePrompt = getFloorPrompt();
      break;
    case 'photozone':
      modePrompt = getPhotozonePrompt();
      break;
    default:
      modePrompt = getFloorPrompt(); // По умолчанию - напольная
  }
  
  let finalPrompt = `${base}

${modePrompt}`;

  if (userInstructions && userInstructions.trim()) {
    finalPrompt += `

ДОПОЛНИТЕЛЬНЫЕ ПОЖЕЛАНИЯ ПОЛЬЗОВАТЕЛЯ:
${userInstructions.trim()}`;
  }
  
  return finalPrompt;
}
